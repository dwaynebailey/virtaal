"""Check that every pyproject.toml [project.dependencies] entry has a
matching module in virtaal-python-deps.yaml, and that every package
that file bundles is at uv.lock's version.

flatpak-builder's sandboxed build has no network access during the
module-build step, so each pip package's source must be pre-declared
there with a pinned URL+sha256. That file is hand-maintained, not
regenerated by CI, so it silently drifts whenever pyproject.toml's
dependency list changes.

Parses both files with plain string/regex extraction rather than
PyYAML: adding a parsing dependency just for this check would be its
own kind of self-defeating drift risk."""

import re
import sys
import tomllib
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent.parent
PYPROJECT = REPO_ROOT / 'pyproject.toml'
UV_LOCK = REPO_ROOT / 'uv.lock'
DEPS_YAML = REPO_ROOT / 'devsupport' / 'packaging' / 'flatpak' / 'virtaal-python-deps.yaml'


def normalize(name):
    """A package/module name, lowercased with '.'/'_'/'-' collapsed to
    '-' so e.g. "fluent.syntax" and "fluent-syntax" compare equal."""
    return re.sub(r'[._-]+', '-', name.strip()).lower()


def pyproject_requirements(text):
    # The list ends at a "]" on its own line; an extra ("pkg[extra]")
    # has its own "]" inside it.
    match = re.search(r'^dependencies\s*=\s*\[(.*?)^\]', text, re.DOTALL | re.MULTILINE)
    if not match:
        raise ValueError('no [project.dependencies] list found in pyproject.toml')
    # Drop full-line comments first - several here contain their own
    # quotes/apostrophes (e.g. "Virtaal's"), which would otherwise be
    # picked up as bogus requirement strings by the regex below.
    block = '\n'.join(
        line for line in match.group(1).splitlines() if not line.strip().startswith('#')
    )
    # Double-quote delimited only, not a "either quote char" alternation:
    # a PEP 508 environment marker (e.g. "pkg==1.0; python_version < '3.11'")
    # has its own single-quoted substring inside the double-quoted
    # requirement string - matching either quote char independently
    # mismatches the pairing and picks up "3.11" as a bogus package name.
    # Every requirement string in this file is double-quoted by
    # convention; content can freely contain single quotes.
    return re.findall(r'"([^"]*)"', block)


def pyproject_dependency_names(text):
    names = []
    for requirement in pyproject_requirements(text):
        # PEP 508: name is the leading identifier, before any version
        # specifier/extra/marker.
        name_match = re.match(r'^([A-Za-z0-9][A-Za-z0-9._-]*)', requirement)
        if name_match:
            names.append(name_match.group(1))
    return names


def locked_versions(text):
    """{normalized name: {version}} from uv.lock; a package can have one
    version per Python range."""
    versions = {}
    for package in tomllib.loads(text)['package']:
        if 'version' in package:
            versions.setdefault(normalize(package['name']), set()).add(package['version'])
    return versions


def flatpak_versions(text):
    """{normalized name: {version}} from every wheel and sdist URL."""
    versions = {}
    for filename in re.findall(r'^\s*url:\s*\S+/([^/\s]+)\s*$', text, re.MULTILINE):
        match = re.fullmatch(r'(.+?)-(\d[^-]*?)(?:-.*\.whl|\.tar\.gz|\.zip)', filename)
        if match:
            versions.setdefault(normalize(match.group(1)), set()).add(match.group(2))
    return versions


def version_mismatches(lock_text, yaml_text):
    """(name, bundled versions, locked versions) for each bundled package
    whose version isn't one uv.lock has. Packages uv.lock doesn't list
    are build tools (rapidfuzz's cmake, ninja, ...)."""
    locked = locked_versions(lock_text)
    return [(name, sorted(bundled), sorted(locked[name]))
            for name, bundled in sorted(flatpak_versions(yaml_text).items())
            if name in locked and not bundled <= locked[name]]


def flatpak_module_names(text):
    # Module entries are "  - name: <module>" at 2-space indent, directly
    # under modules:; nested source/build-command list items sit deeper
    # and never use a "name:" key, so this indentation-scoped pattern
    # can't pick them up by accident.
    return re.findall(r'^  - name:\s*(\S+)\s*$', text, re.MULTILINE)


def installed_names(app_dir):
    """The packages with metadata in an app's own site-packages.
        Distribution names in dist-info directories use '_' for '-'."""
    return {normalize(path.name.split('-', 1)[0])
            for path in Path(app_dir).glob('lib/python3*/site-packages/*.dist-info')}


def check_installed(app_dir):
    """Every dependency must be in the app itself: pip skips one the SDK
        already has, and the runtime Platform may not have it."""
    deps = dict.fromkeys(pyproject_dependency_names(PYPROJECT.read_text(encoding='utf-8')))
    installed = installed_names(app_dir)
    missing = [dep for dep in deps if normalize(dep) not in installed]
    if missing:
        print('pyproject.toml dependencies not installed in %s:' % app_dir)
        for dep in missing:
            print(' - %s' % dep)
        print()
        print('pip leaves out a package the SDK already provides; give its module')
        print('--ignore-installed in %s.' % DEPS_YAML.relative_to(REPO_ROOT))
        return 1
    print('All %d pyproject.toml dependencies are installed in %s.' % (len(deps), app_dir))
    return 0


def main():
    if sys.argv[1:2] == ['--installed']:
        return check_installed(sys.argv[2])
    pyproject_text = PYPROJECT.read_text(encoding='utf-8')
    yaml_text = DEPS_YAML.read_text(encoding='utf-8')
    pyproject_deps = pyproject_dependency_names(pyproject_text)
    module_names = flatpak_module_names(yaml_text)
    known = set()
    for module in module_names:
        if module.lower().startswith('python3-'):
            known.add(normalize(module[len('python3-'):]))

    missing = [dep for dep in pyproject_deps if normalize(dep) not in known]

    if missing:
        print('pyproject.toml [project.dependencies] has package(s) with no matching')
        print('module in %s:' % DEPS_YAML.relative_to(REPO_ROOT))
        for dep in missing:
            print(' - %s (expected a module named python3-%s)' % (dep, dep))
        print()
        print('Add a pinned module entry for each (see the file header for how it was')
        print('originally generated via flatpak-pip-generator).')
        return 1

    mismatches = version_mismatches(UV_LOCK.read_text(encoding='utf-8'), yaml_text)
    if mismatches:
        print('%s bundles a different version than uv.lock has:'
              % DEPS_YAML.relative_to(REPO_ROOT))
        for name, bundled, locked in mismatches:
            print(' - %s %s (uv.lock: %s)' % (name, ', '.join(bundled), ', '.join(locked) or 'none'))
        print()
        print("Update each package's url and sha256 to uv.lock's version.")
        return 1

    print('All %d pyproject.toml dependencies have a matching flatpak module, and'
          ' every bundled package is at uv.lock\'s version.' % len(pyproject_deps))
    return 0


if __name__ == '__main__':
    sys.exit(main())
